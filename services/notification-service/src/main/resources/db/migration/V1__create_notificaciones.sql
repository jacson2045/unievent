CREATE TABLE IF NOT EXISTS notificaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    destinatario_correo VARCHAR(150) NOT NULL,
    tipo VARCHAR(40) NOT NULL,
    titulo VARCHAR(150) NOT NULL,
    mensaje VARCHAR(500) NOT NULL,
    inscripcion_id BIGINT,
    evento_id BIGINT,
    leida BOOLEAN NOT NULL DEFAULT FALSE,
    creada_en TIMESTAMP NOT NULL DEFAULT now(),
    PRIMARY KEY (id)
);

CREATE INDEX IF NOT EXISTS idx_notificaciones_destinatario
    ON notificaciones (destinatario_correo, creada_en DESC);

-- Tabla de idempotencia: un evento (event_id) se procesa una sola vez.
CREATE TABLE IF NOT EXISTS eventos_procesados (
    event_id VARCHAR(64) NOT NULL,
    tipo VARCHAR(40) NOT NULL,
    procesado_en TIMESTAMP NOT NULL DEFAULT now(),
    PRIMARY KEY (event_id)
);
